    /// The theme body the fixtures ship with; tests derive `known` from it, so
    /// nothing here depends on the committed digest list.
    const PRISTINE_JS: &str =
        "export function mount(container, api) {\n  container.textContent = 'hi';\n}\n";

    /// Write one theme folder (`theme.json` + `theme.js`) under `root`.
    fn write_theme(root: &Path, id: &str, js: &str) {
        let dir = root.join(id);
        fs::create_dir_all(&dir).unwrap();
        fs::write(
            dir.join("theme.json"),
            format!(
                r#"{{"manifest_version":2,"id":"{id}","name":"{id}","api_version":1,"entry":"theme.js"}}"#
            ),
        )
        .unwrap();
        fs::write(dir.join("theme.js"), js).unwrap();
    }

    /// The known-digest map for fixtures living in `root`, computed with the
    /// migration's own reader and digest.
    fn known_of(root: &Path, ids: &[&str]) -> HashMap<String, HashSet<String>> {
        let source = DirSource::new(root.to_path_buf());
        ids.iter()
            .map(|id| {
                (
                    (*id).to_string(),
                    HashSet::from([theme_digest(&source.files(id))]),
                )
            })
            .collect()
    }

