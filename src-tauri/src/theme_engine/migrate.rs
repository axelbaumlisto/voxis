//! Retiring pristine builtin theme copies — the migration away from "the user
//! folder holds every bundled theme".
//!
//! Until now the app seeded every bundled theme into `<config>/themes` and
//! never touched an existing copy, so copies froze at the version that was
//! first seeded and shadowed every newer builtin. Builtins now live in the
//! binary, so an untouched copy has no purpose left; this module moves exactly
//! those into `<config>/themes-retired/<id>` (reversible, nothing is deleted).
//!
//! Rules (runs at every startup, idempotently, without a "migration done" flag):
//!
//! - only folder names that are keys of the known-digest list are candidates;
//!   `*_custom` exports and user themes are never looked at;
//! - a candidate's digest is [`theme_digest`] over [`DirSource::files`] — the
//!   same reader the loader and the digest cross-check use, so the migration
//!   judges exactly what the app would load;
//! - digest ∈ known ⇒ move the whole folder; otherwise it stays and keeps
//!   shadowing the builtin (the user's edit wins). Nothing to compare at all
//!   (empty or unreadable folder) is kept too;
//! - a pristine copy that gained an **extra subfolder** still matches: the
//!   digest covers the folder's regular files only, and the loader cannot read
//!   subfolders, so the extra folder cannot change the theme's behavior. The
//!   whole folder, subfolder included, is moved — which keeps this reversible;
//! - a folder holding an entry the digest could not see — a symlinked or
//!   unreadable file, a non-UTF-8 name — is **never** moved: `files()` skips
//!   those, so their content would be missing from the digest and an edit
//!   hiding there would match a known digest. It is kept as edited;
//! - a symlinked theme folder is not followed (and not moved): `symlink_metadata`
//!   decides, so the migration never touches content outside the user folder;
//! - moving is `fs::rename` **only** — never copy-and-delete. A folder that
//!   cannot be renamed (cross-device, locked) stays where it is and is retried
//!   on the next start; it is reported in **neither** list, so nothing claims it
//!   was edited or retired, and no file is ever deleted by this module;
//! - `retired_dir` must be **outside** `user_dir` (Task 8 uses the sibling
//!   `<config>/themes-retired`); a nested destination would move the retire
//!   target along with the themes, so the run is refused;
//! - an error on one folder (unreadable, unmovable) is logged and the loop goes
//!   on with the rest, so a second run finds nothing left to retire.
use super::digest::theme_digest;
use super::source::{DirSource, ThemeSource};
use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};

/// Outcome of one [`retire_pristine_copies`] run; both lists hold theme ids,
/// sorted.
#[derive(Debug, Default)]
pub struct RetireReport {
    /// Pristine copies moved out of the user folder.
    pub retired: Vec<String>,
    /// Candidate ids kept in the user folder: the content matches no known
    /// builtin version, so the copy is the user's.
    pub kept_edited: Vec<String>,
}

/// Every digest a builtin theme has ever shipped with, by theme id, from
/// `known-builtin-digests.json` (generated by
/// `scripts/gen-known-theme-digests.ts` from the git history of
/// `src-tauri/themes`, extended by `scripts/build-themes.ts`).
///
/// Called once at startup; a fresh parse per call is fine. The file is
/// `include_str!`-embedded, so a parse failure is a broken build/repo, not a
/// runtime condition.
pub fn known_builtin_digests() -> HashMap<String, HashSet<String>> {
    let raw: HashMap<String, Vec<String>> =
        serde_json::from_str(include_str!("../../known-builtin-digests.json"))
            .expect("known-builtin-digests.json must be a JSON object of id -> digests");
    raw.into_iter()
        .map(|(id, digests)| (id, digests.into_iter().collect()))
        .collect()
}

/// Move every pristine (untouched) builtin copy from `user_dir` into
/// `retired_dir`, leaving edited copies and non-builtin themes alone.
///
/// `known` is [`known_builtin_digests`]; taking it as a parameter keeps this
/// function testable without the shipped list. `retired_dir` must live outside
/// `user_dir` — a nested destination is refused with an empty report, because
/// retiring into the folder being scanned would sweep the retired themes along.
/// See the module docs for the rules. Never fails: an unreadable user dir (fresh
/// install), a broken folder or a folder that cannot be renamed is logged and
/// the remaining folders are still processed.
pub fn retire_pristine_copies(
    user_dir: &Path,
    retired_dir: &Path,
    known: &HashMap<String, HashSet<String>>,
) -> RetireReport {
    let mut report = RetireReport::default();
    if retired_dir_is_inside_user_dir(retired_dir, user_dir) {
        tracing::warn!(
            "retire: refusing to run: retired dir {:?} is inside the user themes dir {:?}",
            retired_dir,
            user_dir
        );
        return report;
    }
    let entries = match std::fs::read_dir(user_dir) {
        Ok(entries) => entries,
        Err(e) => {
            // Fresh install: the user themes dir does not exist yet.
            if e.kind() != std::io::ErrorKind::NotFound {
                tracing::warn!("retire: cannot read {:?}: {}", user_dir, e);
            }
            return report;
        }
    };

    let source = DirSource::new(user_dir.to_path_buf());
    for entry in entries.flatten() {
        let path = entry.path();
        // `symlink_metadata`, never `is_dir()`: a symlinked theme folder is not
        // a copy this app seeded, and moving it would touch a link.
        let meta = match std::fs::symlink_metadata(&path) {
            Ok(meta) => meta,
            Err(e) => {
                tracing::warn!("retire: cannot stat {:?}: {}", path, e);
                continue;
            }
        };
        if !meta.is_dir() {
            continue;
        }
        let file_name = entry.file_name();
        let Some(id) = file_name.to_str().map(str::to_string) else {
            continue;
        };
        let Some(digests) = known.get(&id) else {
            // Not a builtin id (`_custom` export, user theme): not ours.
            continue;
        };

        // `files()` reports its own read errors and yields an empty list then,
        // which lands in `kept_edited` — keeping a folder we cannot judge.
        let files = source.files(&id);
        // The digest only covers what `files()` could read. Any other entry
        // (a symlink, an unreadable file, a non-UTF-8 name) is invisible to
        // it, so an edit hiding there would still match a known digest —
        // count the entries and keep the folder whenever one was skipped.
        let skipped_entries = non_dir_entry_count(&path) != Some(files.len());
        if files.is_empty() || skipped_entries || !digests.contains(&theme_digest(&files)) {
            report.kept_edited.push(id);
            continue;
        }

        // A move failure is already logged by `move_theme`; the folder stays
        // and is reported in neither list.
        if let Some(dest) = move_theme(&path, retired_dir, &id) {
            tracing::info!("retire: moved pristine theme '{}' to {:?}", id, dest);
            report.retired.push(id);
        }
    }

    report.retired.sort();
    report.kept_edited.sort();
    report
}

/// How many entries of theme folder `dir` are **not** directories — i.e. how
/// many entries `DirSource::files` is supposed to yield. Compared against its
/// result, a difference means an entry was skipped (a symlink, an unreadable
/// file, a non-UTF-8 name) and the folder cannot be judged by digest.
///
/// `None` when the folder or one of its entries cannot be read: unknown is
/// never pristine, so the caller keeps the folder.
fn non_dir_entry_count(dir: &Path) -> Option<usize> {
    let mut count = 0;
    for entry in std::fs::read_dir(dir).ok()? {
        let entry = entry.ok()?;
        // `symlink_metadata`, never `is_dir()`: a symlink is an entry the
        // reader skips, whatever it points at — a linked directory included.
        let meta = std::fs::symlink_metadata(entry.path()).ok()?;
        if !meta.is_dir() {
            count += 1;
        }
    }
    Some(count)
}

/// Move the theme folder `src` into `retired_dir`, under a free name.
/// `None` when the folder could not be moved (already logged); it then stays
/// exactly as it was.
///
/// `fs::rename` only, with no copy-and-delete fallback: a copy that fails
/// halfway leaves two destroyed `themes-retired` entries, while leaving the
/// folder in place costs nothing — the next start tries again.
fn move_theme(src: &Path, retired_dir: &Path, id: &str) -> Option<PathBuf> {
    if let Err(e) = std::fs::create_dir_all(retired_dir) {
        tracing::warn!(
            "retire: cannot create {:?}: {} — keeping {:?}",
            retired_dir,
            e,
            src
        );
        return None;
    }
    let dest = free_destination(retired_dir, id);
    match std::fs::rename(src, &dest) {
        Ok(()) => Some(dest),
        Err(e) => {
            tracing::warn!(
                "retire: cannot move {:?} to {:?}: {} — keeping it",
                src,
                dest,
                e
            );
            None
        }
    }
}

/// First free path for `id` in `retired_dir`: `<id>`, then `<id>.1`, `<id>.2`, …
///
/// `symlink_metadata` rather than `exists()`: even a dangling symlink occupies
/// the name, and `exists()` follows links.
fn free_destination(retired_dir: &Path, id: &str) -> PathBuf {
    let mut candidate = retired_dir.join(id);
    let mut n = 1u32;
    while std::fs::symlink_metadata(&candidate).is_ok() {
        candidate = retired_dir.join(format!("{id}.{n}"));
        n += 1;
    }
    candidate
}

/// Whether `retired_dir` sits inside `user_dir`, i.e. whether retiring would
/// write into the folder being scanned.
///
/// Canonical paths are compared when both exist, so `./themes-retired` and
/// `themes/../themes-retired` are judged as real paths; otherwise (the normal
/// startup case: the retired dir is created lazily) the plain lexical
/// `starts_with` decides.
fn retired_dir_is_inside_user_dir(retired_dir: &Path, user_dir: &Path) -> bool {
    match (retired_dir.canonicalize(), user_dir.canonicalize()) {
        (Ok(retired), Ok(user)) => retired.starts_with(user),
        _ => retired_dir.starts_with(user_dir),
    }
}

