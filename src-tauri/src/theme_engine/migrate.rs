    #[test]
    fn retire_known_builtin_digests_parses_the_shipped_list() {
        let known = known_builtin_digests();

        let digests = known.get("default").expect("'default' must be known");
        assert!(!digests.is_empty(), "'default' has no digest");
        for digest in digests {
            assert_eq!(digest.len(), 64, "not a sha256 hex: {digest}");
            assert!(
                digest
                    .chars()
                    .all(|c| c.is_ascii_hexdigit() && !c.is_ascii_uppercase()),
                "not lowercase hex: {digest}"
            );
        }
    }
